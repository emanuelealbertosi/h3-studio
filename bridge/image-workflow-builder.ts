function node(
  classType: string,
  inputs: Record<string, unknown>,
  title: string,
): ComfyApiNode {
  return { class_type: classType, inputs, _meta: { title } };
}

function loadImageName(file: string) {
  // ComfyUI uses the annotation to resolve files outside its input folder.
  // Removing it makes an image generated by H3 Studio impossible to reuse as
  // an Edit reference because LoadImage falls back to the input directory.
  return file.trim().replaceAll(String.fromCharCode(92), "/");
}

function cloneTemplate(template?: ComfyApiPrompt): ComfyApiPrompt {
  return template ? JSON.parse(JSON.stringify(template)) as ComfyApiPrompt : {};
}

export function assertImageDimensions(width: number, height: number) {
  if (
    !Number.isInteger(width) ||
    !Number.isInteger(height) ||
    width < 64 ||
    height < 64 ||
    width > 4096 ||
    height > 4096 ||
    width % 16 !== 0 ||
    height % 16 !== 0
  ) {
    throw new Error("Larghezza e altezza devono essere multipli di 16 fra 64 e 4096");
  }
  if (width * height > IMAGE_API_MAX_PIXELS) {
    throw new Error("La risoluzione immagine non può superare 4 megapixel");
  }
}

