export function buildMiniMaxH3ImagePrompt(input: {
  prompt: string;
  seed: number;
  width: number;
  height: number;
  filenamePrefix: string;
  settings: MiniMaxH3ImageSettings;
  references: ImageJobReferenceInput[];
  template?: ComfyApiPrompt;
}): ComfyApiPrompt {
  assertImageDimensions(input.width, input.height);
  if (input.references.length > MINIMAX_H3_IMAGE_MAX_REFERENCES) {
    throw new Error("Image H3 supporta al massimo 9 reference");
  }
  const apiPrompt: ComfyApiPrompt = cloneTemplate(input.template);
  for (const id of Object.keys(apiPrompt)) delete apiPrompt[id];

  apiPrompt["1"] = node(
    "UNETLoader",
    { unet_name: input.settings.model, weight_dtype: "default" },
    "MiniMax H3 shared image/video model",
  );
  let textModel: [string, number] = ["1", 0];
  input.settings.loras.forEach((lora, index) => {
    const id = String(40 + index);
    apiPrompt[id] = node(
      "LoraLoaderModelOnly",
      {
        model: textModel,
        lora_name: lora.name,
        strength_model: lora.strength,
      },
      `MiniMax H3 image LoRA ${index + 1}`,
    );
    textModel = [id, 0];
  });
  const turboEnabled = input.settings.steps === 8 && Boolean(input.settings.turboLora);
  if (turboEnabled) {
    apiPrompt["2"] = node(
      "LoraLoaderModelOnly",
      {
        model: textModel,
        lora_name: input.settings.turboLora,
        strength_model: input.settings.turboStrength,
      },
      "MiniMax H3 image Turbo",
    );
    textModel = ["2", 0];
  }
  let editModel = textModel;
  if (input.settings.detailLora) {
    apiPrompt["3"] = node(
      "LoraLoaderModelOnly",
      {
        model: editModel,
        lora_name: input.settings.detailLora,
        strength_model: input.settings.detailStrength,
      },
      "MiniMax H3 image edit detail adapter",
    );
    editModel = ["3", 0];
  }
  apiPrompt["4"] = node(
    "CLIPLoader",
    { clip_name: input.settings.encoder, type: "minimax", device: "default" },
    "MiniMax H3 text/vision encoder",
  );
  apiPrompt["5"] = node(
    "VAELoader",
    { vae_name: input.settings.vae },
    "MiniMax H3 T=1 image VAE",
  );

  const referenceInputs: Record<string, unknown> = {};
  input.references.forEach((reference, index) => {
    const id = String(20 + index);
    apiPrompt[id] = node(
      "LoadImage",
      { image: loadImageName(reference.file) },
      `MiniMax Picture ${index + 1}: ${reference.role}`,
    );
    referenceInputs[index === 0 ? "source_image" : `reference_image_${index + 1}`] = [id, 0];
  });
  const mode = input.references.length === 0
    ? "text_to_image (FL2VA)"
    : input.references.length === 1
      ? "image_to_image (FL2VA)"
      : "reference_edit (REF2VA)";
  const selectedModel = input.references.length === 0 ? textModel : editModel;
  const samplingProfile = input.settings.steps === 8
    ? "Turbo v1.0 | 8 steps"
    : input.settings.steps === 12
      ? "base speed | RES 12 steps"
      : input.settings.steps === 20
        ? "base quality | RES 20 steps"
        : "custom | use controls below";
  apiPrompt["10"] = node(
    "H3ImagePrepare",
    {
      clip: ["4", 0],
      mode,
      prompt: input.prompt,
      width: input.width,
      height: input.height,
      frame_preset: "single image | 1 frame (image VAE)",
      optimize_prompt: true,
      preserve_strength: input.settings.preserveStrength,
      source_fit: "crop_center",
      reference_size: "max_identity_2048",
      vae: ["5", 0],
      ...referenceInputs,
    },
    "MiniMax H3 T2I / I2I / Reference prepare",
  );
  apiPrompt["11"] = node(
    "H3ImageSamplingPreset",
    {
      model: selectedModel,
      sampling_profile: samplingProfile,
      ...(input.settings.steps === 30
        ? {
            custom_sampler: "res_multistep",
            custom_scheduler: "simple",
            custom_steps: 30,
            custom_denoise: 1,
            custom_shift_video: 12,
            custom_shift_audio: 3,
          }
        : {}),
    },
    "MiniMax H3 single-image recipe",
  );
  apiPrompt["12"] = node("RandomNoise", { noise_seed: input.seed }, "MiniMax image seed");
  apiPrompt["13"] = node(
    "BasicGuider",
    { model: ["11", 0], conditioning: ["10", 0] },
    "MiniMax image guider",
  );
  apiPrompt["14"] = node(
    "SamplerCustomAdvanced",
    {
      noise: ["12", 0],
      guider: ["13", 0],
      sampler: ["11", 1],
      sigmas: ["11", 2],
      latent_image: ["10", 1],
    },
    "MiniMax image sampler",
  );
  apiPrompt["15"] = node(
    "H3ImageDecode",
    { samples: ["14", 0], vae: ["5", 0] },
    "MiniMax exact T=1 decode",
  );
  apiPrompt["16"] = node(
    "H3ImageFrameSelector",
    {
      frames: ["15", 0],
      strategy: "decode_recommended",
      manual_index: 0,
      skip_first_frames: 0,
      candidate_start: 0,
      candidate_end: 1,
      similarity_weight: 0.35,
      top_k: 1,
      emit_candidate_batch: false,
      recommended_index: ["15", 3],
      ...(input.references.length ? { source_image: ["20", 0] } : {}),
    },
    "MiniMax single image output",
  );
  apiPrompt["17"] = node(
    "SaveImage",
    { images: ["16", 0], filename_prefix: input.filenamePrefix },
    "Save MiniMax H3 image",
  );
  return apiPrompt;
}

export function buildFlux2KleinEditPrompt(input: {
  prompt: string;
  seed: number;
  width: number;
  height: number;
  filenamePrefix: string;
  settings: ImageEditEngineSettings;
  loras?: EngineLoraSettings[];
  references: ImageJobReferenceInput[];
  template?: ComfyApiPrompt;
}): ComfyApiPrompt {
  assertImageDimensions(input.width, input.height);
  if (input.references.length < 1 || input.references.length > IMAGE_EDIT_MAX_REFERENCES) {
    throw new Error("Flux.2 Klein Edit richiede da 1 a 4 reference");
  }
  const referenceMap = input.references
    .map((reference, index) =>
      "Image " + (index + 1) + " = " +
      REFERENCE_ROLE_LABELS[reference.role] + " (" + reference.name + ")"
    )
    .join("; ");
  const editInstruction = input.prompt + "\n\nReference map: " + referenceMap + ".";
  const apiPrompt: ComfyApiPrompt = cloneTemplate(input.template);
  // Reference chains and optional accelerators are rebuilt for the requested
  // 1–4 inputs. Other nodes in a compatible selected blueprint are preserved.
  for (const id of ["10", "11", "60", "61", "62", "63", "70", "71", "72", "73", "74"]) {
    delete apiPrompt[id];
  }
  for (let id = 20; id <= 39; id += 1) delete apiPrompt[String(id)];
  Object.assign(apiPrompt, {
    "1": node(
      "UNETLoader",
      { unet_name: input.settings.model, weight_dtype: "default" },
      "Flux.2 Klein 4B Distilled FP8",
    ),
    "2": node(
      "CLIPLoader",
      { clip_name: input.settings.encoder, type: "flux2", device: "default" },
      "Flux.2 Klein text encoder",
    ),
    "3": node("VAELoader", { vae_name: input.settings.vae }, "Flux.2 VAE"),
    "4": node(
      "CLIPTextEncode",
      { text: editInstruction, clip: ["2", 0] },
      "Edit instruction",
    ),
    "5": node(
      "ConditioningZeroOut",
      { conditioning: ["4", 0] },
      "Zero negative conditioning",
    ),
    "6": node(
      "EmptyFlux2LatentImage",
      { width: input.width, height: input.height, batch_size: 1 },
      "Flux.2 output canvas",
    ),
    "7": node("RandomNoise", { noise_seed: input.seed }, "Candidate noise"),
    "8": node("KSamplerSelect", { sampler_name: "euler" }, "Euler sampler"),
    "9": node(
      "Flux2Scheduler",
      { steps: input.settings.steps, width: input.width, height: input.height },
      "Flux.2 scheduler",
    ),
  });
  let guidedModel: [string, number] = ["1", 0];
  (input.loras ?? []).forEach((lora, index) => {
    const id = String(70 + index);
    apiPrompt[id] = node(
      "LoraLoaderModelOnly",
      {
        model: guidedModel,
        lora_name: lora.name,
        strength_model: lora.strength,
      },
      `Flux Edit LoRA ${index + 1}`,
    );
    guidedModel = [id, 0];
  });
  if (input.settings.attentionBackend !== "auto") {
    apiPrompt["11"] = node(
      "ModelAttentionBackend",
      {
        model: guidedModel,
        attention: input.settings.attentionBackend,
      },
      "Flux attention backend",
    );
    guidedModel = ["11", 0];
  }
  if (input.settings.kvCacheEnabled) {
    apiPrompt["10"] = node(
      "FluxKVCache",
      { model: guidedModel },
      "Flux reference KV cache",
    );
    guidedModel = ["10", 0];
  }

  let positive: [string, number] = ["4", 0];
  let negative: [string, number] = ["5", 0];
  const referenceMegapixels = 1;
  input.references.forEach((reference, index) => {
    const base = 20 + index * 5;
    const loadId = String(base);
    const scaleId = String(base + 1);
    const encodeId = String(base + 2);
    const positiveId = String(base + 3);
    const negativeId = String(base + 4);
    apiPrompt[loadId] = node(
      "LoadImage",
      { image: loadImageName(reference.file) },
      `Reference ${index + 1}: ${reference.role}`,
    );
    apiPrompt[scaleId] = node(
      "ImageScaleToTotalPixels",
      {
        image: [loadId, 0],
        upscale_method: "nearest-exact",
        megapixels: referenceMegapixels,
        resolution_steps: 1,
      },
      `Normalize reference ${index + 1}`,
    );
    apiPrompt[encodeId] = node(
      "VAEEncode",
      { pixels: [scaleId, 0], vae: ["3", 0] },
      `Encode reference ${index + 1}`,
    );
    apiPrompt[positiveId] = node(
      "ReferenceLatent",
      { conditioning: positive, latent: [encodeId, 0] },
      `Positive reference ${index + 1}`,
    );
    apiPrompt[negativeId] = node(
      "ReferenceLatent",
      { conditioning: negative, latent: [encodeId, 0] },
      `Negative reference ${index + 1}`,
    );
    positive = [positiveId, 0];
    negative = [negativeId, 0];
  });

  apiPrompt["60"] = node(
    "CFGGuider",
    {
      model: guidedModel,
      positive,
      negative,
      cfg: input.settings.cfg,
    },
    "Flux.2 guider",
  );
  apiPrompt["61"] = node(
    "SamplerCustomAdvanced",
    {
      noise: ["7", 0],
      guider: ["60", 0],
      sampler: ["8", 0],
      sigmas: ["9", 0],
      latent_image: ["6", 0],
    },
    "Flux.2 Klein edit sampler",
  );
  apiPrompt["62"] = node(
    "VAEDecode",
    { samples: ["61", 0], vae: ["3", 0] },
    "Decode edited image",
  );
  apiPrompt["63"] = node(
    "SaveImage",
    { images: ["62", 0], filename_prefix: input.filenamePrefix },
    "Save edited image",
  );
  return apiPrompt;
}

